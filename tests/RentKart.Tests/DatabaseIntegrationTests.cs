using Microsoft.EntityFrameworkCore;
using RentKart.Core.Entities;
using RentKart.Core.Enums;
using RentKart.Infrastructure.Data;
using Xunit;

namespace RentKart.Tests;

public class DatabaseIntegrationTests
{
    private const string ConnectionString = "Server=localhost\\SQLEXPRESS;Database=RentKartDb;Trusted_Connection=True;MultipleActiveResultSets=true;TrustServerCertificate=True";

    private ApplicationDbContext CreateDbContext()
    {
        var options = new DbContextOptionsBuilder<ApplicationDbContext>()
            .UseSqlServer(ConnectionString)
            .Options;

        return new ApplicationDbContext(options);
    }

    [Fact]
    public async Task RentKartDb_IsOnline_AndMigrationIsApplied()
    {
        using var context = CreateDbContext();

        var canConnect = await context.Database.CanConnectAsync();
        Assert.True(canConnect, "Expected to connect successfully to RentKartDb on localhost\\SQLEXPRESS.");

        var appliedMigrations = (await context.Database.GetAppliedMigrationsAsync()).ToList();
        Assert.NotEmpty(appliedMigrations);
        Assert.Contains(appliedMigrations, m => m.Contains("InitialRentKartFoundation"));

        var pendingMigrations = (await context.Database.GetPendingMigrationsAsync()).ToList();
        Assert.Empty(pendingMigrations);
    }

    [Fact]
    public async Task RentKartDb_CanExecuteRealInsertReadUpdateAndDelete_WithRelationshipIntegrity()
    {
        using var context = CreateDbContext();
        var testId = Guid.NewGuid().ToString("N")[..8];

        // 1. Create ApplicationUser
        var user = new ApplicationUser
        {
            Id = Guid.NewGuid().ToString(),
            UserName = $"testowner_{testId}@rentkart.local",
            NormalizedUserName = $"TESTOWNER_{testId}@RENTKART.LOCAL",
            Email = $"testowner_{testId}@rentkart.local",
            NormalizedEmail = $"TESTOWNER_{testId}@RENTKART.LOCAL",
            FullName = $"Test Vendor {testId}",
            UserType = UserRole.Business,
            SecurityStamp = Guid.NewGuid().ToString()
        };
        context.Users.Add(user);
        await context.SaveChangesAsync();

        // 2. Create BusinessProfile linked to User
        var business = new BusinessProfile
        {
            UserId = user.Id,
            ShopName = $"Hardware Hub {testId}",
            ContactPhone = "+1-555-0199",
            AddressLine = "123 Market St",
            City = "TechCity",
            State = "CA",
            PostalCode = "94016",
            OperatingHours = "Mon-Fri 08:00 - 18:00",
            Status = BusinessStatus.Approved
        };
        context.BusinessProfiles.Add(business);
        await context.SaveChangesAsync();
        Assert.True(business.Id > 0, "BusinessProfile ID should be generated by DB.");

        // 3. Create Category
        var category = new Category
        {
            Name = $"Demolition Tools {testId}",
            Slug = $"demo-tools-{testId}",
            Description = "Heavy duty verification category",
            DisplayOrder = 1,
            IsActive = true
        };
        context.Categories.Add(category);
        await context.SaveChangesAsync();
        Assert.True(category.Id > 0, "Category ID should be generated by DB.");

        // 4. Create Equipment listing
        var equipment = new Equipment
        {
            BusinessId = business.Id,
            CategoryId = category.Id,
            Title = $"Rotary Hammer Drill {testId}",
            Description = "High impact SDS rotary hammer for concrete work",
            DailyRentalRate = 45.50m,
            SecurityDeposit = 120.00m,
            TotalQuantity = 3,
            Condition = EquipmentCondition.LikeNew,
            Status = EquipmentStatus.Active,
            IsActive = true
        };
        context.Equipments.Add(equipment);
        await context.SaveChangesAsync();
        Assert.True(equipment.Id > 0, "Equipment ID should be generated by DB.");

        // 5. Read back in a new isolated context to verify persistence and relationships
        using (var readContext = CreateDbContext())
        {
            var savedEquipment = await readContext.Equipments
                .Include(e => e.Business)
                .Include(e => e.Category)
                .FirstOrDefaultAsync(e => e.Id == equipment.Id);

            Assert.NotNull(savedEquipment);
            Assert.Equal($"Rotary Hammer Drill {testId}", savedEquipment.Title);
            Assert.Equal(45.50m, savedEquipment.DailyRentalRate);
            Assert.Equal(120.00m, savedEquipment.SecurityDeposit);
            Assert.Equal(3, savedEquipment.TotalQuantity);
            Assert.Equal(EquipmentCondition.LikeNew, savedEquipment.Condition);
            Assert.Equal(EquipmentStatus.Active, savedEquipment.Status);
            Assert.Equal($"Hardware Hub {testId}", savedEquipment.Business.ShopName);
            Assert.Equal($"Demolition Tools {testId}", savedEquipment.Category.Name);

            // 6. Execute UPDATE
            savedEquipment.DailyRentalRate = 52.00m;
            savedEquipment.Description = "Updated rental description with special bit set included";
            savedEquipment.UpdatedAtUtc = DateTime.UtcNow;
            await readContext.SaveChangesAsync();
        }

        // 7. Read again to confirm update persisted
        using (var verifyUpdateContext = CreateDbContext())
        {
            var updatedEquipment = await verifyUpdateContext.Equipments.FindAsync(equipment.Id);
            Assert.NotNull(updatedEquipment);
            Assert.Equal(52.00m, updatedEquipment.DailyRentalRate);
            Assert.Equal("Updated rental description with special bit set included", updatedEquipment.Description);
            Assert.NotNull(updatedEquipment.UpdatedAtUtc);
        }

        // 8. Clean up created test entities
        using (var cleanupContext = CreateDbContext())
        {
            var eq = await cleanupContext.Equipments.FindAsync(equipment.Id);
            if (eq != null) cleanupContext.Equipments.Remove(eq);

            var cat = await cleanupContext.Categories.FindAsync(category.Id);
            if (cat != null) cleanupContext.Categories.Remove(cat);

            var bp = await cleanupContext.BusinessProfiles.FindAsync(business.Id);
            if (bp != null) cleanupContext.BusinessProfiles.Remove(bp);

            var u = await cleanupContext.Users.FindAsync(user.Id);
            if (u != null) cleanupContext.Users.Remove(u);

            await cleanupContext.SaveChangesAsync();
        }

        // 9. Verify deletion completed
        using (var postCleanupContext = CreateDbContext())
        {
            var exists = await postCleanupContext.Equipments.AnyAsync(e => e.Id == equipment.Id);
            Assert.False(exists, "Test equipment should be cleaned up.");
        }
    }
}
