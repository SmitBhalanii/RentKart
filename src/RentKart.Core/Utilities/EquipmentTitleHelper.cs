using System.Text.RegularExpressions;

namespace RentKart.Core.Utilities;

public static class EquipmentTitleHelper
{
    private static readonly Regex HexOrGuidSuffixPattern = new(
        @"\s*[-–—]?\s*(?:Test\s*)?[a-f0-9]{16,36}\b", 
        RegexOptions.IgnoreCase | RegexOptions.Compiled);

    private static readonly Regex PureHashOrGuidPattern = new(
        @"^[a-f0-9\-_]{8,}$", 
        RegexOptions.IgnoreCase | RegexOptions.Compiled);

    private static readonly Regex PureTestPattern = new(
        @"^(?:test|demo|sample|temporary|placeholder|item\s*\d*)$", 
        RegexOptions.IgnoreCase | RegexOptions.Compiled);

    /// <summary>
    /// Cleanses any internal GUIDs, hex hashes, or test tags from public-facing equipment titles.
    /// </summary>
    public static string FormatCleanTitle(string? title)
    {
        if (string.IsNullOrWhiteSpace(title))
        {
            return "Professional Equipment";
        }

        var cleaned = title.Trim();

        // Strip trailing hex/GUID hashes generated by automated integration test runners
        cleaned = HexOrGuidSuffixPattern.Replace(cleaned, string.Empty).Trim();

        // Strip trailing "- Test" or similar markers
        if (cleaned.EndsWith(" - Test", StringComparison.OrdinalIgnoreCase))
        {
            cleaned = cleaned[..^7].Trim();
        }
        else if (cleaned.EndsWith("-Test", StringComparison.OrdinalIgnoreCase))
        {
            cleaned = cleaned[..^5].Trim();
        }

        if (cleaned.Equals("Updated Title Safely", StringComparison.OrdinalIgnoreCase))
        {
            return "Professional Equipment";
        }

        if (string.IsNullOrWhiteSpace(cleaned))
        {
            return "Professional Equipment";
        }

        return cleaned;
    }

    /// <summary>
    /// Validates that a business listing title follows professional, human-readable marketplace standards.
    /// </summary>
    public static bool IsProfessionalTitle(string? title, out string? errorMessage)
    {
        if (string.IsNullOrWhiteSpace(title))
        {
            errorMessage = "Equipment title is required.";
            return false;
        }

        var trimmed = title.Trim();

        if (trimmed.Length < 3 || trimmed.Length > 200)
        {
            errorMessage = "Equipment title must be between 3 and 200 characters.";
            return false;
        }

        if (!trimmed.Any(char.IsLetter))
        {
            errorMessage = "Equipment title must contain descriptive letters, brand, or model details.";
            return false;
        }

        if (PureHashOrGuidPattern.IsMatch(trimmed))
        {
            errorMessage = "Equipment title cannot consist solely of internal identifiers, hashes, or GUIDs.";
            return false;
        }

        if (PureTestPattern.IsMatch(trimmed))
        {
            errorMessage = "Please enter a descriptive equipment name instead of generic placeholder text.";
            return false;
        }

        errorMessage = null;
        return true;
    }
}

